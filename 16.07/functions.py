#Задание 1 "Продвинутый sum"

def sum_ignore_non_numbers(items):
    # Создаем переменную для хранения суммы, начинаем с 0
    total = 0
    
    # Проходим по каждому элементу в списке
    for element in items:
        # Проверяем: является ли элемент числом?
        # type() возвращает тип элемента
        # сравниваем с int (целое число) или float (число с точкой)
        if type(element) == int or type(element) == float:
            # Если да - добавляем это число к общей сумме
            total = total + element
    
    #возвращаем результат
    return total


