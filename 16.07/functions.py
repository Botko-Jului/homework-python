def common_strings(list1, list2, ignore_case=True):

    #создаем пустой список для результатов
    result = []

    #проходим по каждому элементу из первого списка
    for item1 in list1:

        #проходим по каждому элементу во втором списке
        for item2 in list2:

            #проверяем условие
            if ignore_case == True:

                #приводим оба элемента к нижнему регистру и сравниваем
                if item1.lower() == item2.lower():

                    # Добавляем элемент в нижнем регистре в результат
                    result.append(item1.lower())
                    break  #выход, после найденного совпадения
            else:
                # Если регистр важен - сравниваем как есть
                if item1 == item2:
                    # Добавляем элемент в нижнем регистре
                    result.append(item1.lower())
                    break  #выход
    
    #возвращаем результат
    return result

