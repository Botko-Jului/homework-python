#Задание 3 "Среднее значение"

def average(*args):

# Проверяем: есть ли вообще аргументы?
    if len(args) == 0:

        #ecли аргументов нет - возвращаем 0
        return 0

    # Считаем сумму всех чисел
    total = 0
    for number in args:
        total = total + number
    
    #cчитаем количество чисел
    count = len(args)
    
    #вычисляем среднее
    average_value = total / count
    
    #возвращаем среднее
    return average_value

